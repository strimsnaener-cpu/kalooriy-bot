WEEK_PLAN = ["A", "active", "B", "active", "C", "active", "rest"]
DAY_NAMES = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье"]


def workout_for(weekday, week):
    key = WEEK_PLAN[weekday]
    if key == "active":
        title, ex = ACTIVE
    elif key == "rest":
        title, ex = REST
    else:
        title, ex = STRENGTH[key]
    lvl = level_for_week(week)
    return key, title, [(name, reps[lvl], sets[lvl], tip) for name, reps, sets, tip in ex]


def workout_text(weekday, week):
    key, title, ex = workout_for(weekday, week)
    L = [f"<b>{DAY_NAMES[weekday]} — {title}</b>", f"<i>Неделя {week}</i>\n"]
    for i, (name, reps, sets, tip) in enumerate(ex, 1):
        line = f"{i}. {name}"
        if reps != "—":
            line += f" — <b>{sets}×{reps}</b>" if sets > 1 else f" — <b>{reps}</b>"
        L.append(line)
        if tip:
            L.append(f"   <i>{tip}</i>")
    if key in STRENGTH:
        L.append("\n⏱ Отдых между подходами 60–90 сек. Пей воду.")
        L.append("⚠️ Если что-то болит (не просто устал, а именно боль) — остановись.")
    return "\n".join(L)


def week_plan_text(week):
    L = [f"📅 <b>План на неделю</b> (неделя {week})\n"]
    for d in range(7):
        _, title, _ = workout_for(d, week)
        L.append(f"{DAY_NAMES[d]}: {title}")
    L.append("\nНагрузка растёт сама: на 3-й и 5-й неделе станет чуть больше подходов и повторов.")
    return "\n".join(L)
